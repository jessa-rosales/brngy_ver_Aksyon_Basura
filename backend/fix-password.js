const bcrypt = require('bcrypt');
const pool = require('./src/db'); // Adjust this path to your db.js

async function fix() {
  try {
    const saltRounds = 10;
    const newHash = await bcrypt.hash('sagun123', saltRounds);
    
    await pool.query(
      "UPDATE users SET password = $1 WHERE email = 'sagun@gmail.com'", 
      [newHash]
    );
    
    console.log("-----------------------------------------");
    console.log("✅ PASSWORD FIXED SUCCESSFULLY");
    console.log("New Hash generated by your system:", newHash);
    console.log("-----------------------------------------");
    process.exit();
  } catch (err) {
    console.error("Error fixing password:", err);
    process.exit(1);
  }
}

fix();